//! Original display profile for the observed UC5-2S DATA format.
//! No device configuration, TX, ADC or HV data. No calibration or acoustic units.
use odb_convex_decoder::{ImageProfile, Result, RgbaFrame, Session};
use serde_json::{Value, json};
use std::cell::RefCell;
pub const PROFILE: &str = "uc5-normalized-binomial-v1";
pub const WIDTH: usize = 512;
pub const HEIGHT: usize = 512;
#[derive(Clone, Copy)]
pub struct Display {
    pub gain_db: f32,
    pub dynamic_range_db: f32,
    pub tgc_slope_db: f32,
    pub persistence: f32,
}
impl Default for Display {
    fn default() -> Self {
        // Display choices, not measured tissue attenuation or probe calibration.
        Self {
            gain_db: -8.,
            dynamic_range_db: 48.,
            tgc_slope_db: 0.,
            persistence: 0.25,
        }
    }
}
impl Display {
    fn validate(self) -> Result<()> {
        if !self.gain_db.is_finite()
            || !(-60. ..=60.).contains(&self.gain_db)
            || !self.dynamic_range_db.is_finite()
            || !(12. ..=120.).contains(&self.dynamic_range_db)
            || !self.tgc_slope_db.is_finite()
            || !(-60. ..=60.).contains(&self.tgc_slope_db)
            || !self.persistence.is_finite()
            || !(0. ..=0.9).contains(&self.persistence)
        {
            return Err("Display settings out of bounded finite domain".into());
        }
        Ok(())
    }
}
/// Half of the symmetric length16 binomial FIR: coefficients of (1+z^-1)^15/2^15.
/// Integer construction is exact on native and WASM, with unity DC gain.
pub fn binomial16_half() -> [f32; 8] {
    let mut c = 1u32;
    std::array::from_fn(|i| {
        if i > 0 {
            c = c * (16 - i as u32) / i as u32;
        }
        c as f32 / 32768.
    })
}
pub fn configuration() -> Value {
    // These are observed DATA-format facts; they do not request hardware settings.
    json!({"parameters":{"A":2,"B":0,"C":4,"D":4,"E":4},
      "grouping":{"schema_version":"convex-b-grouping-settings-v1","b_capacity_bytes":2097152,"m_capacity_bytes":2097152,"m_line_count":1,"bm_header_26":0,"bm_header_28":0,"epoch_policy":"new-organizer-per-observed-epoch-v1"},
      "settings":{"schema_version":"convex-pipeline-settings-v1",
        "bfsp":{"schema_version":"convex-bfsp-settings-v1","depth_index":0,"selector_index":0,"line_words":1800},
        "dtgc":{"schema_version":"convex-dtgc-settings-v1","bank_selector_0x48":0,"gain":0.,"dynamic_range":48.,"tgc_controls":[0.,0.,0.,0.,0.,0.]},
        "sri":{"enhancement":0,"correlation_index":0},
        "dsc":{"schema_version":"convex-dsc-settings-v1","depth_index":0,"width":WIDTH,"height":HEIGHT,"gray_map":0,"tint_map":0},"max_groups":128}})
}
pub fn image_profile(display: Display) -> Result<ImageProfile> {
    display.validate()?;
    let mut settings = configuration()["settings"].clone();
    settings["dtgc"]["dynamic_range"] = json!(display.dynamic_range_db);
    // The rendering sector is a chosen normalized view, NOT a measured scan angle.
    let theta = std::f32::consts::PI / 3.;
    let mut parameters = [0u8; 40];
    for (i, v) in [
        (2, WIDTH as u32),
        (3, HEIGHT as u32),
        (6, 1f32.to_bits()),
        (7, theta.to_bits()),
        (8, 1f32.to_bits()),
        (9, (theta / 2.).cos().to_bits()),
    ] {
        parameters[4 * i..4 * i + 4].copy_from_slice(&v.to_le_bytes());
    }
    let tgc = std::array::from_fn(|sample| display.tgc_slope_db * (sample as f32 / 1023.));
    Ok(ImageProfile {
        settings,
        bfsp_coefficients: binomial16_half(),
        // 1800words ->900 ushort4 vectors ->768 valid FIR positions ->3072 upsampled values.
        // Reduce those3072 values to the core's1024 samples. No physical sampling clock inferred.
        bfsp_downsample: 3,
        dtgc_tgc: tgc,
        // Required core bookkeeping range; this scalar is unused by pixel evaluation.
        dtgc_depth: 2.,
        dtgc_gain: display.gain_db,
        dtgc_dr: 255. / display.dynamic_range_db,
        // Disable adaptive compound mixing; retain the shared processing/lifecycle implementation.
        compound_window: 1,
        compound_coef0: 0.,
        compound_threshold_a: 0.,
        compound_threshold_b: 1.,
        temporal_correlation: display.persistence,
        dsc_parameters: parameters,
        display_map: std::array::from_fn(|i| (i / 4) as u8),
    })
}
pub fn manifest(display: Display) -> Result<Value> {
    display.validate()?;
    Ok(
        json!({"profile":PROFILE,"license":"AGPL-3.0-or-later","purpose":"reconstruction-only",
        "input_format":"observed mode0/P896/N32, line_words1800, four u16 envelope lanes",
        "filter":"(1+z^-1)^15 / 2^15; 16tap binomial, generated by integer recurrence",
        "gain_db":display.gain_db,"dynamic_range_db":display.dynamic_range_db,
        "tgc":"slope_db * sample_index /1023; default flat","tgc_slope_db":display.tgc_slope_db,
        "temporal_persistence":display.persistence,"palette":"identity grayscale, generated",
        "geometry":"chosen normalized60degree sector, unit radius; no metric scale",
        "alpha":"output is opaque; core's fourth LUT component is an intensity index",
        "width":WIDTH,"height":HEIGHT,"transmit_commands":0,"external_resource_files":0,
        "calibrated":false,"vendor_profile_equivalence_claimed":false}),
    )
}
pub struct OpenSession {
    engine: Session,
}
impl OpenSession {
    pub fn new(display: Display) -> Result<Self> {
        let profile = image_profile(display)?;
        let mut conf = configuration();
        conf["settings"] = profile.settings.clone();
        let mut engine = Session::from_profile(&conf, profile)?;
        engine.allow_continuous();
        Ok(Self { engine })
    }
    pub fn push(&mut self, bytes: &[u8]) -> Result<Vec<RgbaFrame>> {
        let frames = self.engine.push_rgba(bytes)?;
        Ok(opaque(frames))
    }
    pub fn finish(&mut self) -> Result<Vec<RgbaFrame>> {
        let frames = self.engine.finish_rgba()?;
        Ok(opaque(frames))
    }
    /// Update all processing histories without rasterizing discarded frames.
    pub fn advance(&mut self, bytes: &[u8]) -> Result<()> {
        self.engine.advance(bytes)
    }
}
fn opaque(mut frames: Vec<RgbaFrame>) -> Vec<RgbaFrame> {
    for f in &mut frames {
        for pixel in f.rgba.as_chunks_mut::<4>().0 {
            pixel[3] = 255;
        }
    }
    frames
}
thread_local! {static ENGINE:RefCell<Option<OpenSession>>=const{RefCell::new(None)};static OUTPUT:RefCell<Vec<u8>>=const{RefCell::new(Vec::new())};}
#[unsafe(no_mangle)]
pub extern "C" fn odb_builtin_profile() -> u32 {
    1
}
#[unsafe(no_mangle)]
pub extern "C" fn odb_live_api() -> u32 {
    1
}
#[unsafe(no_mangle)]
pub extern "C" fn odb_alloc(n: usize) -> *mut u8 {
    if n > 4194304 {
        return std::ptr::null_mut();
    }
    Box::into_raw(vec![0u8; n].into_boxed_slice()) as *mut u8
}
/// # Safety
/// Pointer/length must describe the exact live allocation returned by odb_alloc.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn odb_free(p: *mut u8, n: usize) {
    if !p.is_null() {
        unsafe {
            drop(Box::from_raw(std::ptr::slice_from_raw_parts_mut(p, n)));
        }
    }
}
fn encode(frames: Vec<RgbaFrame>, png: bool) -> Result<Vec<u8>> {
    let mut out = (frames.len() as u32).to_le_bytes().to_vec();
    for f in frames {
        let b = if png {
            odb_convex_decoder::encode_rgba_png(WIDTH, HEIGHT, &f.rgba)?
        } else {
            f.rgba
        };
        out.extend(f.sequence.to_le_bytes());
        out.extend((b.len() as u32).to_le_bytes());
        out.extend(b);
    }
    Ok(out)
}
fn initialize(bytes: &[u8]) -> Result<Vec<u8>> {
    let opts: Value = serde_json::from_slice(bytes).map_err(|e| e.to_string())?;
    let obj = opts
        .as_object()
        .ok_or("Require explicit reconstruction options")?;
    if obj.len() != 1 || obj.get("purpose") != Some(&json!("reconstruction")) {
        return Err("This original profile supports reconstruction only; USB acquisition is not implemented".into());
    }
    let session = OpenSession::new(Display::default())?;
    ENGINE.with(|s| *s.borrow_mut() = Some(session));
    let mut v = manifest(Display::default())?;
    v["ready"] = json!(true);
    Ok(serde_json::to_vec(&v).unwrap())
}
/// # Safety
/// Pointer/length must identify initialized readable bytes for the duration of the call.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn odb_call(op: u32, p: *const u8, n: usize) -> i32 {
    if p.is_null() || n > 4194304 {
        return -1;
    }
    let bytes = unsafe { std::slice::from_raw_parts(p, n) };
    let result = match op {
        7 | 8 => initialize(bytes),
        2 | 9 => ENGINE
            .with(|s| {
                s.borrow_mut()
                    .as_mut()
                    .ok_or("Initialize reconstruction first")?
                    .push(bytes)
            })
            .and_then(|f| encode(f, op == 2)),
        5 | 10 => ENGINE
            .with(|s| {
                s.borrow_mut()
                    .as_mut()
                    .ok_or("Initialize reconstruction first")?
                    .finish()
            })
            .and_then(|f| encode(f, op == 5)),
        11 => odb_convex_decoder::encode_rgba_png(WIDTH, HEIGHT, bytes),
        12 => ENGINE
            .with(|s| {
                s.borrow_mut()
                    .as_mut()
                    .ok_or("Initialize reconstruction first")?
                    .advance(bytes)
            })
            .and_then(|()| encode(Vec::new(), false)),
        4 => Err(
            "This original profile cannot produce probe configuration or transmit commands".into(),
        ),
        _ => Err("Unsupported reconstruction operation".into()),
    };
    let (status, b) = match result {
        Ok(b) => (0, b),
        Err(e) => (-1, e.into_bytes()),
    };
    OUTPUT.with(|o| *o.borrow_mut() = b);
    status
}
#[unsafe(no_mangle)]
pub extern "C" fn odb_output_ptr() -> *const u8 {
    OUTPUT.with(|o| o.borrow().as_ptr())
}
#[unsafe(no_mangle)]
pub extern "C" fn odb_output_len() -> usize {
    OUTPUT.with(|o| o.borrow().len())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn binomial_filter_has_unit_dc_gain_and_zero_nyquist_response() {
        let half = binomial16_half();
        let full: Vec<_> = half.iter().chain(half.iter().rev()).copied().collect();
        assert_eq!(full.iter().sum::<f32>(), 1.);
        assert_eq!(
            full.iter()
                .enumerate()
                .map(|(i, v)| if i % 2 == 0 { *v } else { -*v })
                .sum::<f32>(),
            0.
        );
        assert!(full.iter().all(|c| *c > 0.));
        // Analytic binomial magnitude at omega=pi/2: cos(pi/4)^15.
        let (re, im) = full
            .iter()
            .enumerate()
            .fold((0f64, 0f64), |(re, im), (n, &c)| {
                let a = n as f64 * std::f64::consts::FRAC_PI_2;
                (re + c as f64 * a.cos(), im - c as f64 * a.sin())
            });
        assert!((re.hypot(im) - 2f64.powf(-7.5)).abs() < 1e-12);
    }
    #[test]
    fn display_inputs_are_finite_bounded_and_never_activate_hardware() {
        for invalid in [
            Display {
                gain_db: f32::NAN,
                ..Display::default()
            },
            Display {
                dynamic_range_db: 0.,
                ..Display::default()
            },
            Display {
                persistence: 1.,
                ..Display::default()
            },
            Display {
                tgc_slope_db: f32::INFINITY,
                ..Display::default()
            },
        ] {
            assert!(image_profile(invalid).is_err());
        }
        assert!(initialize(br#"{}"#).is_err());
        assert!(initialize(br#"{"purpose":"acquisition"}"#).is_err());
        assert!(initialize(br#"{"purpose":"reconstruction","gain":0}"#).is_err());
        assert!(initialize(br#"{"purpose":"reconstruction"}"#).is_ok());
        let b = [0u8; 512];
        let status = unsafe { odb_call(4, b.as_ptr(), b.len()) };
        assert_eq!(status, -1);
        OUTPUT.with(|o| assert!(String::from_utf8_lossy(&o.borrow()).contains("cannot produce")));
    }
}
